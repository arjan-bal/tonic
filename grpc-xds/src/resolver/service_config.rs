//! The service config generated by the xDS resolver.
//!
//! These types mirror the configs of the LB policies the resolver names, for
//! serialization only. They are kept in the resolver, as in gRPC Go, so that
//! the LB policies don't depend on how the resolver uses them.

use std::collections::BTreeMap;

use serde::Serialize;

/// Name of the cluster manager LB policy.
const CLUSTER_MANAGER_POLICY_NAME: &str = "xds_cluster_manager_experimental";
/// Name of the CDS LB policy.
const CDS_POLICY_NAME: &str = "cds_experimental";

/// Returns a service config that uses the cluster manager policy, with one
/// child per cluster in `clusters` named "cluster:<name>", whose child policy
/// is CDS for that cluster.
pub(super) fn cds_cluster_manager_service_config<'a>(
    clusters: impl IntoIterator<Item = &'a str>,
) -> String {
    let children = clusters
        .into_iter()
        .map(|cluster| {
            let cds = CdsConfig {
                cluster: cluster.to_owned(),
            };
            let child = CdsChild {
                child_policy: LbPolicyList::new(CDS_POLICY_NAME, cds),
            };
            (cluster_child_name(cluster), child)
        })
        .collect();
    let service_config = ServiceConfig {
        load_balancing_config: LbPolicyList::new(
            CLUSTER_MANAGER_POLICY_NAME,
            CdsClusterManagerConfig { children },
        ),
    };
    serde_json::to_string(&service_config).expect("service config is serializable")
}

/// Returns the name of the cluster manager child for `cluster`. The config
/// selector routes RPCs to the child with this name.
pub(super) fn cluster_child_name(cluster: &str) -> String {
    format!("cluster:{cluster}")
}

/// The service config generated by the xDS resolver: just an LB policy.
#[derive(Serialize)]
struct ServiceConfig {
    #[serde(rename = "loadBalancingConfig")]
    load_balancing_config: LbPolicyList<CdsClusterManagerConfig>,
}

/// A gRFC A24 LoadBalancingConfig list naming one policy:
/// `[{ "<policy name>": <config> }]`.
#[derive(Serialize)]
struct LbPolicyList<T>(Vec<BTreeMap<&'static str, T>>);

impl<T> LbPolicyList<T> {
    fn new(policy_name: &'static str, config: T) -> Self {
        Self(vec![BTreeMap::from([(policy_name, config)])])
    }
}

/// Config of the cluster manager policy in which every child is a CDS policy
/// for one cluster.
#[derive(Serialize)]
struct CdsClusterManagerConfig {
    /// Children keyed by name. Sorted, so the output is deterministic.
    children: BTreeMap<String, CdsChild>,
}

/// A child of [`CdsClusterManagerConfig`].
#[derive(Serialize)]
struct CdsChild {
    #[serde(rename = "childPolicy")]
    child_policy: LbPolicyList<CdsConfig>,
}

/// Config of the CDS policy.
#[derive(Serialize)]
struct CdsConfig {
    /// Name of the cluster to load balance across.
    cluster: String,
}
